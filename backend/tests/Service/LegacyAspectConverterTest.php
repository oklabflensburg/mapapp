<?php

namespace App\Tests\Service;

use App\Service\LegacyAspectConverter;
use Doctrine\DBAL\Connection;
use Symfony\Bundle\FrameworkBundle\Test\KernelTestCase;

final class LegacyAspectConverterTest extends KernelTestCase
{
    private Connection $connection;
    private string $path;

    protected function setUp(): void
    {
        self::bootKernel();
        $this->connection = static::getContainer()->get('doctrine')->getConnection();
        $this->connection->beginTransaction();
        $schema = 'aspect_conversion_'.bin2hex(random_bytes(5));
        $this->connection->executeStatement('CREATE SCHEMA '.$schema);
        $this->connection->executeStatement('SET LOCAL search_path TO '.$schema);
        foreach ([
            'CREATE TABLE aspect_types (id INT PRIMARY KEY, name TEXT)',
            'CREATE TABLE aspect_attributes (id INT PRIMARY KEY, aspect_type_id INT, key TEXT, position INT, kind TEXT, attribute_values JSON)',
            'CREATE TABLE aspect_preferences (id INT PRIMARY KEY, attribute_id INT, label TEXT, attribute_values JSON)',
            'CREATE TABLE street_part_aspects (id INT PRIMARY KEY, group_id INT, aspect_type_id INT, created_by_user_id INT, approved BOOLEAN, position INT, attribute_values JSON)',
            'CREATE TABLE tags (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, key TEXT, value TEXT, translations JSON, updated_at TIMESTAMP, UNIQUE(key, value))',
            'CREATE TABLE node_group_tags (group_id INT, tag_id INT, created_by_user_id INT, approved BOOLEAN, UNIQUE(group_id, tag_id, created_by_user_id))',
            'CREATE TABLE user_tag_priorities (user_id INT, tag TEXT, priority TEXT)',
            "INSERT INTO aspect_types VALUES (1, 'sidewalk')",
            "INSERT INTO aspect_attributes VALUES (1, 1, 'width', 1, 'range', '[\"< 1 m\",\"> 2 m\"]')",
            "INSERT INTO aspect_preferences VALUES (42, 1, 'Legacy wide footwalk', '[\"> 2 m\"]')",
            "INSERT INTO street_part_aspects VALUES (1, 10, 1, 7, true, 1, '{\"width\":\"> 2 m\"}'), (2, 10, 1, 8, false, 5, '{\"width\":\"1 m – 2 m\"}')",
            "INSERT INTO user_tag_priorities VALUES (7, 'aspect:42', 'prefer')",
        ] as $sql) $this->connection->executeStatement($sql);
        $this->path = tempnam(sys_get_temp_dir(), 'legacy-aspects');
        file_put_contents($this->path, file_get_contents(dirname(__DIR__, 2).'/config/examples/aspect-catalog.json'));
    }

    protected function tearDown(): void
    {
        $this->connection->rollBack();
        unlink($this->path);
        parent::tearDown();
    }

    public function testPreservesValuesApprovalAttributionPreferencesAndReruns(): void
    {
        $converter = new LegacyAspectConverter($this->connection, $this->path);
        try {
            $converter->convert(verifyOnly: true);
            self::fail('Unconverted rows must block table removal.');
        } catch (\RuntimeException $exception) {
            self::assertStringContainsString('convert-legacy', $exception->getMessage());
        }
        $converter->convert();
        $converter->convert();
        $converter->convert(verifyOnly: true);
        $tags = $this->connection->fetchAllAssociative('SELECT t.key, t.value, gt.created_by_user_id, gt.approved FROM node_group_tags gt JOIN tags t ON t.id = gt.tag_id ORDER BY t.key');
        self::assertCount(2, $tags);
        self::assertSame('way.footwalk.1.width', $tags[0]['key']);
        self::assertSame('>2', $tags[0]['value']);
        self::assertSame(7, $tags[0]['created_by_user_id']);
        self::assertTrue($tags[0]['approved']);
        self::assertSame('1-2', $tags[1]['value']);
        self::assertFalse($tags[1]['approved']);
        $catalog = json_decode(file_get_contents($this->path), true);
        $preference = array_column($catalog['preferences'], null, 'key')['aspect:42'];
        self::assertSame(['>2'], $preference['values']);
        self::assertSame('footwalk', $preference['type']);
        self::assertSame('prefer', $this->connection->fetchOne("SELECT priority FROM user_tag_priorities WHERE tag = 'aspect:42'"));
        $attribute = $catalog['types'][0]['attributes'][0];
        self::assertSame('1 m – 2 m', $attribute['labels']['1-2']);
        self::assertNotContains('1-2', $attribute['values']); // retired data stays retired
    }

    public function testFreshInstallationCreatesNoAspectTables(): void
    {
        foreach (['street_part_aspects', 'aspect_preferences', 'aspect_attributes', 'aspect_types'] as $table) {
            $this->connection->executeStatement('DROP TABLE '.$table);
        }
        require_once dirname(__DIR__, 2).'/migrations/Version20261107073924.php';
        require_once dirname(__DIR__, 2).'/migrations/Version20261107083314.php';
        foreach ([\DoctrineMigrations\Version20261107073924::class, \DoctrineMigrations\Version20261107083314::class] as $class) {
            $migration = new $class($this->connection, new \Psr\Log\NullLogger());
            $migration->up(new \Doctrine\DBAL\Schema\Schema());
            self::assertSame([], $migration->getSql());
        }
    }

    public function testCollisionLeavesDatabaseAndFileUnchanged(): void
    {
        $this->connection->executeStatement("INSERT INTO tags (key, value, translations, updated_at) VALUES ('way.footwalk.1.width', '<1', '{}', CURRENT_TIMESTAMP)");
        $id = $this->connection->lastInsertId();
        $this->connection->executeStatement('INSERT INTO node_group_tags VALUES (10, ?, 7, false)', [$id]);
        $before = file_get_contents($this->path);
        try {
            (new LegacyAspectConverter($this->connection, $this->path))->convert();
            self::fail('Existing conflicting tags must abort conversion.');
        } catch (\RuntimeException $exception) {
            self::assertStringContainsString('collision', $exception->getMessage());
        }
        self::assertSame($before, file_get_contents($this->path));
        self::assertSame(1, (int) $this->connection->fetchOne('SELECT COUNT(*) FROM node_group_tags'));
    }

    public function testUnknownAspectStopsWithoutWriting(): void
    {
        $this->connection->executeStatement("UPDATE street_part_aspects SET attribute_values = '{\"unmapped\":\"yes\"}' WHERE id = 2");
        $before = file_get_contents($this->path);
        try {
            (new LegacyAspectConverter($this->connection, $this->path))->convert();
            self::fail('Unknown legacy attributes must abort conversion.');
        } catch (\RuntimeException $exception) {
            self::assertStringContainsString('Cannot map', $exception->getMessage());
        }
        self::assertSame($before, file_get_contents($this->path));
        self::assertSame(0, (int) $this->connection->fetchOne('SELECT COUNT(*) FROM node_group_tags'));
    }
}
